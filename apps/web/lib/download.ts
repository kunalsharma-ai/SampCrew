import 'server-only';
import { NextResponse } from 'next/server';
import { ApiError, api, apiDownload, apiRaw } from './api';

const PASS_HEADERS = ['content-type', 'content-length', 'content-disposition'];

function pass(res: Response) {
  const headers = new Headers({ 'cache-control': 'private, no-store', 'x-content-type-options': 'nosniff' });
  for (const h of PASS_HEADERS) {
    const v = res.headers.get(h);
    if (v) headers.set(h, v);
  }
  return new NextResponse(res.body, { headers });
}

/** A file behind a signed link: the API checks access and audits it when issuing the link, the file streams through here. */
export async function streamSignedFile(linkPath: string) {
  try {
    const link = await api<{ path: string }>(linkPath, { method: 'POST' });
    const file = await apiRaw(link.path);
    if (!file.ok || !file.body) return new NextResponse('File not found', { status: 404 });
    return pass(file);
  } catch (e) {
    if (e instanceof ApiError) return new NextResponse(e.status === 401 ? 'Sign in again to download this file' : 'File not found', { status: e.status === 401 ? 401 : 404 });
    throw e;
  }
}

/** An export (Excel, PDF) generated by the API for the signed-in person. */
export async function streamExport(path: string) {
  const res = await apiDownload(path);
  if (!res.ok || !res.body) {
    const e = (await res.json().catch(() => ({}))) as { error?: { message?: string } };
    return new NextResponse(e.error?.message ?? 'Export not available', { status: [401, 403, 404, 422].includes(res.status) ? res.status : 400 });
  }
  return pass(res);
}
