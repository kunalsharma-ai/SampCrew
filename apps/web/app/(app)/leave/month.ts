/** Month arithmetic for the leave calendar, shared by the server page and the client calendar. */
export const pad = (n: number) => String(n).padStart(2, '0');
export const iso = (y: number, m: number, d: number) => `${y}-${pad(m)}-${pad(d)}`;

/** The first and last day of a YYYY-MM month, and its neighbours. */
export function monthRange(month: string) {
  const [y, m] = month.split('-').map(Number) as [number, number];
  const last = new Date(Date.UTC(y, m, 0)).getUTCDate();
  const prev = m === 1 ? `${y - 1}-12` : `${y}-${pad(m - 1)}`;
  const next = m === 12 ? `${y + 1}-01` : `${y}-${pad(m + 1)}`;
  return { y, m, from: iso(y, m, 1), to: iso(y, m, last), last, prev, next };
}

