import { Alert, Card, CardBody, CardHeader, PageHeader, Table, TBody, TD, TH, THead, TR } from '@crew/ui';
import type { Metadata } from 'next';
import Link from 'next/link';
import { load } from '@/lib/api';
import { amount, days, monthLabel } from '../../payroll/labels';
import type { Payslip } from '../../payroll/types';
import { PrintButton } from './print-button';

export const metadata: Metadata = { title: 'Payslip' };

export default async function PayslipPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const p = await load<Payslip>(`/payslips/${id}`);
  const money = (v: string) => amount(v, p.currency);
  const of = (kind: string) => p.lines.filter((l) => l.kind === kind);
  const section = (title: string, kind: string, total?: string) => {
    const lines = of(kind);
    if (!lines.length) return null;
    return (
      <Card>
        <CardHeader title={title} />
        <Table>
          <THead><tr><TH>Item</TH><TH className="print:hidden">How</TH><TH className="text-right">Amount</TH></tr></THead>
          <TBody>
            {lines.map((l) => <TR key={l.code}><TD>{l.name}</TD><TD className="text-[0.8125rem] text-fg-muted print:hidden">{l.explanation}</TD><TD className="whitespace-nowrap text-right tabular-nums">{money(l.amount)}</TD></TR>)}
            {total && <TR><TD className="font-semibold">Total</TD><TD className="print:hidden" /><TD className="whitespace-nowrap text-right font-semibold tabular-nums">{money(total)}</TD></TR>}
          </TBody>
        </Table>
      </Card>
    );
  };
  return (
    <>
      <PageHeader
        eyebrow={p.legalEntityName}
        title={`Payslip for ${monthLabel(p.month)}`}
        description={`${p.name} (${p.code}) · paid on ${p.payDate}`}
        actions={<div className="flex items-center gap-3 print:hidden"><PrintButton /><Link className="text-sm font-medium text-accent hover:underline" href="/payslips">All payslips</Link></div>}
      />
      <div className="grid gap-6">
        {p.isDemo && <Alert tone="info">Demo workspace: this payslip is made from sample data.</Alert>}
        <Card>
          <CardBody>
            <dl className="grid grid-cols-2 gap-x-6 gap-y-3 text-[0.8125rem] sm:grid-cols-4">
              <div><dt className="text-fg-muted">Designation</dt><dd className="font-medium">{p.designation ?? '–'}</dd></div>
              <div><dt className="text-fg-muted">Department</dt><dd className="font-medium">{p.department ?? '–'}</dd></div>
              <div><dt className="text-fg-muted">Location</dt><dd className="font-medium">{p.location ?? '–'}</dd></div>
              <div><dt className="text-fg-muted">Date of joining</dt><dd className="font-medium">{p.dateOfJoining}</dd></div>
              <div><dt className="text-fg-muted">Days in month</dt><dd className="font-medium tabular-nums">{p.daysInPeriod}</dd></div>
              <div><dt className="text-fg-muted">Loss of pay</dt><dd className="font-medium tabular-nums">{days(p.lopDays)}</dd></div>
              <div><dt className="text-fg-muted">Paid days</dt><dd className="font-medium tabular-nums">{days(p.paidDays)}</dd></div>
              <div><dt className="text-fg-muted">Net pay</dt><dd className="text-base font-semibold tabular-nums">{money(p.net)}</dd></div>
            </dl>
          </CardBody>
        </Card>
        <div className="grid gap-6 lg:grid-cols-2">
          {section('Earnings', 'earning', p.gross)}
          {section('Deductions', 'deduction', p.deductions)}
        </div>
        {section('Reimbursements (not taxable)', 'reimbursement', p.reimbursements)}
        {section('Employer contributions (paid by your employer on top of your pay)', 'employer', p.employerContributions)}
        <div className="grid gap-6 lg:grid-cols-2">
          <Card>
            <CardHeader title="This financial year" description={`From ${p.yearToDate.financialYearFrom} to this payslip`} />
            <CardBody>
              <dl className="grid grid-cols-3 gap-3 text-[0.8125rem]">
                <div><dt className="text-fg-muted">Gross</dt><dd className="font-medium tabular-nums">{money(p.yearToDate.gross)}</dd></div>
                <div><dt className="text-fg-muted">Income tax</dt><dd className="font-medium tabular-nums">{money(p.yearToDate.tds)}</dd></div>
                <div><dt className="text-fg-muted">Net</dt><dd className="font-medium tabular-nums">{money(p.yearToDate.net)}</dd></div>
              </dl>
            </CardBody>
          </Card>
          <Card className="print:hidden">
            <CardHeader title="How this was worked out" />
            <CardBody><ul className="list-disc space-y-1 pl-5 text-[0.8125rem]">{p.explanation.map((e, i) => <li key={i}>{e}</li>)}</ul></CardBody>
          </Card>
        </div>
        <p className="text-xs text-fg-subtle">Generated by SampCrew from {p.workspaceName}’s finalised payroll. Questions about this payslip go to your payroll team.</p>
      </div>
    </>
  );
}
